// Copies the authored backend adapters from src/lib-src/ into src/lib/.
//
// Why this exists: the repo's .gitignore has a generic `lib/` rule (meant for
// ReScript build output) that also swallows src/lib/. So the hand-written
// adapters that used to live in src/lib/ were never tracked by git. Rather
// than loosen that rule, we keep the source of truth in the tracked
// src/lib-src/ directory and regenerate src/lib/ at build/dev start. The rest
// of the app keeps importing from '../lib/...' unchanged.
//
// Edit src/lib-src/* — never src/lib/* (it is overwritten on every build).

import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const srcDir = join(here, '..', 'src', 'lib-src')
const outDir = join(here, '..', 'src', 'lib')

const banner =
  '// AUTO-GENERATED by scripts/sync-backends.mjs — edit src/lib-src/ instead.\n'

await mkdir(outDir, { recursive: true })

const files = (await readdir(srcDir)).filter((f) => f.endsWith('.ts'))
for (const file of files) {
  const body = await readFile(join(srcDir, file), 'utf8')
  await writeFile(join(outDir, file), banner + body)
}

console.log(`sync-backends: copied ${files.length} file(s) to src/lib/`)
